const provinceByName = new Map(IRAN_PROVINCES.map((item) => [item.name, item]));

export function iranProvinceNames(): readonly string[] {
  return IRAN_PROVINCES.map((item) => item.name);
}

export function isIranProvince(name: string): boolean {
  return provinceByName.has(name);
}

export function citiesOfProvince(province: string): readonly string[] {
  return provinceByName.get(province)?.cities ?? [];
}

export function isCityInProvince(province: string, city: string): boolean {
  return citiesOfProvince(province).includes(city);
}
